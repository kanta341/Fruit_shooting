class DoubleConv(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()

        self.net = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),

            nn.Conv2d(out_channels, out_channels, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
        )

    def forward(self, x):
        return self.net(x)


class UpBlockNoSkip(nn.Module):
    """
    Decoder-only upsample block.
    Used after returning to 128px to reach 256 and 512.
    """
    def __init__(self, channels):
        super().__init__()
        self.up = nn.ConvTranspose2d(channels, channels, kernel_size=2, stride=2)
        self.conv = DoubleConv(channels, channels)

    def forward(self, x):
        x = self.up(x)
        x = self.conv(x)
        return x


class UNetRGBA128To512(nn.Module):
    """
    Input:
      [B, 1, 128, 128]

    Output:
      [B, 4, 512, 512]

    Structure:
      encoder:
        128 -> 64 -> 32 -> 16

      decoder with skips:
        16 -> 32 -> 64 -> 128

      extra decoder:
        128 -> 256 -> 512
    """
    def __init__(self, in_channels=1, out_channels=4, base_channels=24):
        super().__init__()

        c1 = base_channels
        c2 = base_channels * 2
        c3 = base_channels * 4
        c4 = base_channels * 8

        self.enc1 = DoubleConv(in_channels, c1)      # 128
        self.pool1 = nn.MaxPool2d(2)

        self.enc2 = DoubleConv(c1, c2)               # 64
        self.pool2 = nn.MaxPool2d(2)

        self.enc3 = DoubleConv(c2, c3)               # 32
        self.pool3 = nn.MaxPool2d(2)

        self.bottleneck = DoubleConv(c3, c4)         # 16

        self.up3 = nn.ConvTranspose2d(c4, c3, kernel_size=2, stride=2)  # 32
        self.dec3 = DoubleConv(c3 + c3, c3)

        self.up2 = nn.ConvTranspose2d(c3, c2, kernel_size=2, stride=2)  # 64
        self.dec2 = DoubleConv(c2 + c2, c2)

        self.up1 = nn.ConvTranspose2d(c2, c1, kernel_size=2, stride=2)  # 128
        self.dec1 = DoubleConv(c1 + c1, c1)

        # Additional decoder side: 128 -> 256 -> 512
        self.up0 = UpBlockNoSkip(c1)   # 256
        self.up_minus1 = UpBlockNoSkip(c1)  # 512

        self.out_conv = nn.Conv2d(c1, out_channels, kernel_size=1)

    def forward(self, x):
        e1 = self.enc1(x)
        e2 = self.enc2(self.pool1(e1))
        e3 = self.enc3(self.pool2(e2))

        b = self.bottleneck(self.pool3(e3))

        d3 = self.up3(b)
        d3 = torch.cat([d3, e3], dim=1)
        d3 = self.dec3(d3)

        d2 = self.up2(d3)
        d2 = torch.cat([d2, e2], dim=1)
        d2 = self.dec2(d2)

        d1 = self.up1(d2)
        d1 = torch.cat([d1, e1], dim=1)
        d1 = self.dec1(d1)

        d0 = self.up0(d1)          # 256
        d_minus1 = self.up_minus1(d0)  # 512

        return self.out_conv(d_minus1)


