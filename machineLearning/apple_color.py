def pil_rgb_to_tensor(img: Image.Image) -> torch.Tensor:
    arr = np.asarray(img).astype(np.float32) / 255.0
    arr = np.transpose(arr, (2, 0, 1))
    return torch.from_numpy(arr)


def pil_gray_mask_to_tensor(img: Image.Image) -> torch.Tensor:
    arr = np.asarray(img).astype(np.float32) / 255.0
    return torch.from_numpy(arr).unsqueeze(0)


def tensor_to_rgb_numpy(t: torch.Tensor) -> np.ndarray:
    x = t.detach().cpu().clamp(0, 1).numpy()
    return np.transpose(x, (1, 2, 0))


def tensor_to_gray_numpy(t: torch.Tensor) -> np.ndarray:
    return t.detach().cpu().clamp(0, 1).squeeze(0).numpy()


def make_checkerboard(h, w, tile=24):
    yy, xx = np.indices((h, w))
    board = ((yy // tile + xx // tile) % 2).astype(np.float32)
    board = 0.85 + board * 0.10
    return np.stack([board, board, board], axis=-1)


def alpha_composite_on_checker(rgb: np.ndarray, alpha: np.ndarray) -> np.ndarray:
    bg = make_checkerboard(rgb.shape[0], rgb.shape[1], tile=24)
    alpha3 = alpha[..., None]
    return rgb * alpha3 + bg * (1.0 - alpha3)


def load_border_image_as_line_pil(path: Path, out_size: int) -> Image.Image:
    """
    Source:
      white background + black line.

    Returned PIL:
      line = 255
      background = 0
    """
    img = Image.open(path).convert("L")

    if img.size != (out_size, out_size):
        img = img.resize((out_size, out_size), Image.NEAREST)

    arr = np.asarray(img)
    mask = (arr < 128).astype(np.uint8) * 255
    return Image.fromarray(mask).convert("L")


def create_rgb_and_alpha_from_color_image(
    path: Path,
    out_size: int,
    white_threshold: int,
) -> tuple[Image.Image, Image.Image]:
    """
    Color target:
      original RGB image with white background.
      resize to out_size.
      alpha = non-white area.
    """
    rgb = Image.open(path).convert("RGB")

    if rgb.size != (out_size, out_size):
        rgb = rgb.resize((out_size, out_size), Image.BICUBIC)

    arr = np.asarray(rgb)

    alpha = np.logical_not(
        (arr[:, :, 0] >= white_threshold) &
        (arr[:, :, 1] >= white_threshold) &
        (arr[:, :, 2] >= white_threshold)
    ).astype(np.uint8) * 255

    alpha_img = Image.fromarray(alpha).convert("L")
    return rgb, alpha_img


