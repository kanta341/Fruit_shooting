@torch.no_grad()
def save_validation_samples(
    model,
    dataset,
    epoch,
    save_dir,
    num_samples=6,
    seed=123,
):
    model.eval()

    if len(dataset) == 0:
        return None

    rng = np.random.default_rng(seed + epoch)
    idxs = rng.choice(len(dataset), size=min(num_samples, len(dataset)), replace=False)

    fig, axes = plt.subplots(len(idxs), 6, figsize=(22, 3.5 * len(idxs)))

    if len(idxs) == 1:
        axes = np.expand_dims(axes, axis=0)

    for row, idx in enumerate(idxs):
        border, rgb_target, alpha_target, meta = dataset[int(idx)]

        x = border.unsqueeze(0).to(DEVICE)
        output = model(x)

        rgb_pred = torch.sigmoid(output[:, 0:3])[0].cpu()
        alpha_pred = torch.sigmoid(output[:, 3:4])[0].cpu()
        alpha_bin = (alpha_pred >= CONFIG["alpha_threshold"]).float()

        border_np = tensor_to_gray_numpy(border)
        rgb_target_np = tensor_to_rgb_numpy(rgb_target)
        alpha_target_np = tensor_to_gray_numpy(alpha_target)

        rgb_pred_np = tensor_to_rgb_numpy(rgb_pred)
        alpha_pred_np = tensor_to_gray_numpy(alpha_pred)
        composite_np = alpha_composite_on_checker(
            rgb_pred_np,
            tensor_to_gray_numpy(alpha_bin),
        )

        axes[row, 0].imshow(border_np, cmap="gray", vmin=0, vmax=1)
        axes[row, 0].set_title(f"Input border 128\n{meta['name']}")
        axes[row, 0].axis("off")

        axes[row, 1].imshow(rgb_target_np)
        axes[row, 1].set_title("GT RGB 512")
        axes[row, 1].axis("off")

        axes[row, 2].imshow(alpha_target_np, cmap="gray", vmin=0, vmax=1)
        axes[row, 2].set_title("GT Alpha 512")
        axes[row, 2].axis("off")

        axes[row, 3].imshow(rgb_pred_np)
        axes[row, 3].set_title("Pred RGB 512")
        axes[row, 3].axis("off")

        axes[row, 4].imshow(alpha_pred_np, cmap="gray", vmin=0, vmax=1)
        axes[row, 4].set_title("Pred Alpha 512")
        axes[row, 4].axis("off")

        axes[row, 5].imshow(composite_np)
        axes[row, 5].set_title("Pred RGBA checker")
        axes[row, 5].axis("off")

    plt.tight_layout()

    save_path = Path(save_dir) / f"epoch_{epoch:03d}.png"
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.close()

    return save_path


