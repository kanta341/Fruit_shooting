@torch.no_grad()
def compute_batch_metrics(output, rgb_target, alpha_target, eps=1e-6):
    rgb_pred = torch.sigmoid(output[:, 0:3, :, :])
    alpha_prob = torch.sigmoid(output[:, 3:4, :, :])
    alpha_pred = (alpha_prob >= CONFIG["alpha_threshold"]).float()

    inter = (alpha_pred * alpha_target).sum(dim=(1, 2, 3))
    pred_sum = alpha_pred.sum(dim=(1, 2, 3))
    target_sum = alpha_target.sum(dim=(1, 2, 3))
    union = pred_sum + target_sum - inter

    alpha_dice = ((2.0 * inter + eps) / (pred_sum + target_sum + eps)).mean().item()
    alpha_iou = ((inter + eps) / (union + eps)).mean().item()

    mask = alpha_target
    rgb_mae_inside = (torch.abs(rgb_pred - rgb_target) * mask).sum() / (mask.sum() * 3.0 + eps)
    rgb_mae_inside = rgb_mae_inside.item()

    return {
        "alpha_dice": alpha_dice,
        "alpha_iou": alpha_iou,
        "rgb_mae_inside": rgb_mae_inside,
    }


