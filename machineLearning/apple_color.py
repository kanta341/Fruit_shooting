def build_or_load_split(pairs, exp_dir: Path):
    split_path = exp_dir / "split.json"

    if CONFIG["reuse_existing_split"] and split_path.exists():
        print("\nLoading existing split:", split_path)
        with open(split_path, "r", encoding="utf-8") as f:
            split_data = json.load(f)

        pair_dict = {x["stem"]: x for x in pairs}

        train_pairs = [pair_dict[stem] for stem in split_data["train"] if stem in pair_dict]
        val_pairs = [pair_dict[stem] for stem in split_data["val"] if stem in pair_dict]
        test_pairs = [pair_dict[stem] for stem in split_data["test"] if stem in pair_dict]

        return train_pairs, val_pairs, test_pairs

    rng = random.Random(CONFIG["random_seed"])
    pairs_copy = pairs[:]
    rng.shuffle(pairs_copy)

    n = len(pairs_copy)
    n_train = int(n * CONFIG["train_ratio"])
    n_val = int(n * CONFIG["val_ratio"])

    train_pairs = pairs_copy[:n_train]
    val_pairs = pairs_copy[n_train:n_train + n_val]
    test_pairs = pairs_copy[n_train + n_val:]

    with open(split_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                "train": [x["stem"] for x in train_pairs],
                "val": [x["stem"] for x in val_pairs],
                "test": [x["stem"] for x in test_pairs],
            },
            f,
            indent=2,
            ensure_ascii=False
        )

    print("\nSaved new split:", split_path)
    return train_pairs, val_pairs, test_pairs


