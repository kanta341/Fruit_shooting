def dice_loss_from_logits(logits, targets, eps=1e-6):
    probs = torch.sigmoid(logits)

    probs = probs.view(probs.size(0), -1)
    targets = targets.view(targets.size(0), -1)

    intersection = (probs * targets).sum(dim=1)
    denominator = probs.sum(dim=1) + targets.sum(dim=1)

    dice = (2.0 * intersection + eps) / (denominator + eps)
    return 1.0 - dice.mean()


def rgba_colorization_loss(output, rgb_target, alpha_target, eps=1e-6):
    """
    output:
      [B,4,512,512]
      output[:,0:3] = RGB logits
      output[:,3:4] = alpha logits
    """
    rgb_logit = output[:, 0:3, :, :]
    alpha_logit = output[:, 3:4, :, :]

    rgb_pred = torch.sigmoid(rgb_logit)

    # RGB loss only inside alpha target
    mask = alpha_target
    rgb_l1 = torch.abs(rgb_pred - rgb_target)
    rgb_inside_loss = (rgb_l1 * mask).sum() / (mask.sum() * 3.0 + eps)

    # Alpha loss on all pixels
    alpha_bce = F.binary_cross_entropy_with_logits(alpha_logit, alpha_target)
    alpha_dice = dice_loss_from_logits(alpha_logit, alpha_target, eps=eps)

    total = (
        CONFIG["rgb_loss_weight"] * rgb_inside_loss
        + CONFIG["alpha_bce_weight"] * alpha_bce
        + CONFIG["alpha_dice_weight"] * alpha_dice
    )

    bg_rgb_loss = torch.tensor(0.0, device=output.device)

    if CONFIG["background_rgb_weight"] > 0:
        bg_mask = 1.0 - alpha_target
        white = torch.ones_like(rgb_pred)

        bg_l1 = torch.abs(rgb_pred - white)
        bg_rgb_loss = (bg_l1 * bg_mask).sum() / (bg_mask.sum() * 3.0 + eps)

        total = total + CONFIG["background_rgb_weight"] * bg_rgb_loss

    return total, {
        "loss": total.detach(),
        "rgb_inside_loss": rgb_inside_loss.detach(),
        "alpha_bce": alpha_bce.detach(),
        "alpha_dice": alpha_dice.detach(),
        "bg_rgb_loss": bg_rgb_loss.detach(),
    }


