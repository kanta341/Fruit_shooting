def list_image_files(path: Path):
    exts = ["*.png", "*.PNG", "*.jpg", "*.JPG", "*.jpeg", "*.JPEG", "*.webp", "*.WEBP"]
    files = []
    for ext in exts:
        files.extend(path.glob(ext))
    return sorted(files)


def collect_pairs(border_dir: Path, color_dir: Path):
    border_list = list_image_files(border_dir)
    color_list = list_image_files(color_dir)

    print("\nBorder files found:", len(border_list))
    print("Color files found:", len(color_list))

    print("Border examples:", [p.name for p in border_list[:10]])
    print("Color examples:", [p.name for p in color_list[:10]])

    border_files = {p.stem: p for p in border_list}
    color_files = {p.stem: p for p in color_list}

    common_stems = sorted(
        set(border_files.keys()) & set(color_files.keys()),
        key=lambda x: int(x) if x.isdigit() else x
    )

    pairs = []
    for stem in common_stems:
        pairs.append({
            "name": f"{stem}.png",
            "stem": stem,
            "border_path": border_files[stem],
            "color_path": color_files[stem],
        })

    missing_in_color = sorted(set(border_files.keys()) - set(color_files.keys()))
    missing_in_border = sorted(set(color_files.keys()) - set(border_files.keys()))

    print("Matched pairs:", len(pairs))
    print("Missing in color:", len(missing_in_color))
    print("Missing in border:", len(missing_in_border))

    if missing_in_color:
        print("Missing in color examples:", missing_in_color[:10])
    if missing_in_border:
        print("Missing in border examples:", missing_in_border[:10])

    return pairs


