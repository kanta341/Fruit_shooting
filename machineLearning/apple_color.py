def image_count(path: Path) -> int:
    count = 0
    for ext in ["*.png", "*.PNG", "*.jpg", "*.JPG", "*.jpeg", "*.JPEG", "*.webp", "*.WEBP"]:
        count += len(list(path.glob(ext)))
    return count


def find_dataset_dir(root: Path, target_parts: tuple[str, str]) -> Path:
    """
    Example:
      target_parts=("border_dataset", "apple")
      target_parts=("color_dataset", "apple")
    """
    candidates = []

    for p in root.rglob(target_parts[-1]):
        if not p.is_dir():
            continue

        parts = p.parts
        if len(parts) >= len(target_parts):
            if tuple(parts[-len(target_parts):]) == target_parts:
                candidates.append(p)

    if len(candidates) == 0:
        print("\nDirectories under extracted root:")
        for p in root.rglob("*"):
            if p.is_dir():
                print(p)
        raise FileNotFoundError(f"Could not find directory ending with: {target_parts}")

    best = max(candidates, key=image_count)

    print(f"\nFound {target_parts}: {best}")
    print("Image count:", image_count(best))

    return best


