def iter_ndjson_records(path: Path, max_records: int, recognized_only: bool = True):
    count = 0

    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if count >= max_records:
                break

            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                continue

            if recognized_only and not obj.get("recognized", False):
                continue

            drawing = obj.get("drawing")
            if drawing is None:
                continue

            yield obj
            count += 1


