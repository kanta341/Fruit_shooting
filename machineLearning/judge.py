def conv_block(x, filters, dropout=0.0):
    x = layers.SeparableConv2D(
        filters,
        kernel_size=3,
        padding="same",
        use_bias=False
    )(x)
    x = layers.BatchNormalization()(x)
    x = layers.ReLU()(x)

    x = layers.SeparableConv2D(
        filters,
        kernel_size=3,
        padding="same",
        use_bias=False
    )(x)
    x = layers.BatchNormalization()(x)
    x = layers.ReLU()(x)

    if dropout > 0:
        x = layers.Dropout(dropout)(x)

    return x


def build_model(img_size=IMG_SIZE, num_classes=NUM_CLASSES):
    inputs = keras.Input(shape=(img_size, img_size, 1), name="image")

    x = inputs

    # 256x256
    x = conv_block(x, 24, dropout=0.00)
    x = layers.MaxPooling2D(pool_size=2)(x)

    # 128x128
    x = conv_block(x, 48, dropout=0.05)
    x = layers.MaxPooling2D(pool_size=2)(x)

    # 64x64
    x = conv_block(x, 96, dropout=0.08)
    x = layers.MaxPooling2D(pool_size=2)(x)

    # 32x32
    x = conv_block(x, 128, dropout=0.10)
    x = layers.MaxPooling2D(pool_size=2)(x)

    # 16x16
    x = conv_block(x, 192, dropout=0.12)
    x = layers.MaxPooling2D(pool_size=2)(x)

    # 8x8
    x = conv_block(x, 256, dropout=0.15)

    x = layers.GlobalAveragePooling2D()(x)

    x = layers.Dense(128, activation="relu")(x)
    x = layers.Dropout(0.30)(x)

    x = layers.Dense(64, activation="relu")(x)
