def bytes_feature(value: bytes):
    return tf.train.Feature(bytes_list=tf.train.BytesList(value=[value]))


def float_list_feature(values):
    return tf.train.Feature(float_list=tf.train.FloatList(value=values))


def int64_feature(value: int):
    return tf.train.Feature(int64_list=tf.train.Int64List(value=[value]))


def str_feature(value: str):
    return tf.train.Feature(bytes_list=tf.train.BytesList(value=[value.encode("utf-8")]))


def serialize_example(image_uint8, label_float32, target_name, category_name):
    feature = {
        "image_raw": bytes_feature(image_uint8.tobytes()),
        "label": float_list_feature(label_float32.astype(np.float32).tolist()),
        "target": str_feature(target_name),
        "category": str_feature(category_name),
        "height": int64_feature(IMG_SIZE),
        "width": int64_feature(IMG_SIZE),
        "channels": int64_feature(1),
    }

    example = tf.train.Example(features=tf.train.Features(feature=feature))
    return example.SerializeToString()


def split_name_for_random():
    r = random.random()

    if r < TRAIN_RATIO:
        return "train"
    elif r < TRAIN_RATIO + VAL_RATIO:
        return "val"
    else:
        return "test"


