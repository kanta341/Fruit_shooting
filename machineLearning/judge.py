def category_to_url(category: str) -> str:
    encoded = urllib.parse.quote(category, safe="")
    return f"{BASE_URL}/{encoded}.ndjson"


def safe_filename(category: str) -> str:
    return category.replace(" ", "_")


def download_category(category: str, out_dir: Path = NDJSON_DIR) -> Path | None:
    out_path = out_dir / f"{safe_filename(category)}.ndjson"

    if out_path.exists() and out_path.stat().st_size > 0:
        print(f"Already exists: {out_path}")
        return out_path

    url = category_to_url(category)
    print(f"Downloading {category}: {url}")

    try:
        urllib.request.urlretrieve(url, out_path)

    except urllib.error.HTTPError as e:
        if out_path.exists():
            out_path.unlink()

        if e.code == 404:
            print(f"WARNING: Category not found, skipped: {category}")
            return None

        raise RuntimeError(f"Failed to download {category} from {url}") from e

    except Exception as e:
        if out_path.exists():
            out_path.unlink()
        raise RuntimeError(f"Failed to download {category} from {url}") from e

    return out_path


