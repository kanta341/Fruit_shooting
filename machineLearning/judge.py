def scores_to_labels(scores, threshold=THRESHOLD):
    max_scores = np.max(scores, axis=1)
    argmaxes = np.argmax(scores, axis=1)

    labels = []

    for max_score, idx in zip(max_scores, argmaxes):
        if max_score < threshold:
            labels.append("none")
        else:
            labels.append(CLASS_NAMES[idx])

    return np.array(labels)


def y_to_true_labels(y):
    labels = []

    for row in y:
        if np.sum(row) == 0:
            labels.append("none")
        else:
            labels.append(CLASS_NAMES[int(np.argmax(row))])

    return np.array(labels)


def collect_predictions(model, ds):
    all_scores = []
    all_y = []

    for batch_x, batch_y in tqdm(ds, desc="Predicting"):
        scores = model.predict(batch_x, verbose=0)
        all_scores.append(scores)
        all_y.append(batch_y.numpy())

    all_scores = np.concatenate(all_scores, axis=0)
    all_y = np.concatenate(all_y, axis=0)

    return all_scores, all_y


def evaluate_threshold(model, ds, threshold=THRESHOLD):
    scores, y_true = collect_predictions(model, ds)

    pred_labels = scores_to_labels(scores, threshold=threshold)
    true_labels = y_to_true_labels(y_true)

    acc = np.mean(pred_labels == true_labels)

    labels = CLASS_NAMES + ["none"]

    cm = pd.DataFrame(
        0,
        index=[f"true_{x}" for x in labels],
        columns=[f"pred_{x}" for x in labels],
    )

    for t, p in zip(true_labels, pred_labels):
        cm.loc[f"true_{t}", f"pred_{p}"] += 1

    return acc, cm, scores, pred_labels, true_labels, y_true


