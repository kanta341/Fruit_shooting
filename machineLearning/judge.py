def classify_image_array(
    image_array,
    model,
    threshold: float = THRESHOLD,
    smoothing_prev=None,
    smoothing_alpha: float = 0.30,
):
    img = image_array.astype(np.float32)

    if img.ndim == 2:
        img = img[..., None]

    if img.shape != (IMG_SIZE, IMG_SIZE, 1):
        raise ValueError(
            f"Expected shape {(IMG_SIZE, IMG_SIZE, 1)}, got {img.shape}"
        )

    img = np.clip(img, 0.0, 1.0)

    scores = model.predict(img[None, ...], verbose=0)[0]

    if smoothing_prev is not None:
        scores = (1.0 - smoothing_alpha) * smoothing_prev + smoothing_alpha * scores

    max_score = float(np.max(scores))
    max_idx = int(np.argmax(scores))

    if max_score < threshold:
        label = "none"
    else:
        label = CLASS_NAMES[max_idx]

    return {
        "label": label,
        "max_score": max_score,
        "threshold": threshold,
        "scores": {
            CLASS_NAMES[i]: float(scores[i])
            for i in range(NUM_CLASSES)
        },
        "smoothed_scores": scores,
    }


