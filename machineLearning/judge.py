def parse_for_training(serialized):
    feature_description = {
        "image_raw": tf.io.FixedLenFeature([], tf.string),
        "label": tf.io.FixedLenFeature([NUM_CLASSES], tf.float32),
    }

    example = tf.io.parse_single_example(serialized, feature_description)

    image = tf.io.decode_raw(example["image_raw"], tf.uint8)
    image = tf.reshape(image, [IMG_SIZE, IMG_SIZE, 1])
    image = tf.cast(image, tf.float32)

    label = example["label"]

    return image, label


def augment_image_tf(image, label):
    image = tf.cond(
        tf.random.uniform(()) < 0.5,
        lambda: tf.image.flip_left_right(image),
        lambda: image,
    )

    pad = 10

    image_padded = tf.pad(
        image,
        [[pad, pad], [pad, pad], [0, 0]],
        constant_values=0.0
    )

    image = tf.image.random_crop(
        image_padded,
        size=[IMG_SIZE, IMG_SIZE, 1]
    )

    keep_prob = tf.random.uniform((), 0.965, 1.0)

    mask = tf.cast(
        tf.random.uniform(tf.shape(image)) < keep_prob,
        tf.float32
    )

    image = image * mask
    image = tf.clip_by_value(image, 0.0, 1.0)

    return image, label


def make_dataset(tfrecord_path, training: bool, repeat: bool = False):
    ds = tf.data.TFRecordDataset(
        str(tfrecord_path),
        num_parallel_reads=AUTOTUNE
    )

    if training:
        ds = ds.shuffle(
            buffer_size=8192,
            seed=SEED,
            reshuffle_each_iteration=True
        )

    ds = ds.map(parse_for_training, num_parallel_calls=AUTOTUNE)

    if training:
        ds = ds.map(augment_image_tf, num_parallel_calls=AUTOTUNE)

    if repeat:
        ds = ds.repeat()

    ds = ds.batch(BATCH_SIZE, drop_remainder=False)
    ds = ds.prefetch(AUTOTUNE)

    return ds


